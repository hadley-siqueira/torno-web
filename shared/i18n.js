export const MESSAGES = { pt, en };

export function t(lang, key, params = {}) {
  const dict = MESSAGES[lang] || MESSAGES[DEFAULT_LANG];
  const s = dict[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

/** Formata uma mensagem do interpretador ({ code, params }), preenchendo o nome da ferramenta. */
export function formatMessage(lang, m) {
  const params = { ...(m.params || {}) };
  if (params.t !== undefined && params.name === undefined) params.name = toolName(getTool(params.t), lang);
  return t(lang, m.code, params);
}
